def 记载(项目: str, 条件: bool, 证据: str) -> None:
    结果.append({"最终复核项": 项目, "状态": "通过" if 条件 else "失败", "证据": str(证据)})


def 比较文件(来源: Path, 镜像: Path, 标签: str) -> None:
    条件 = 来源.is_file() and 镜像.is_file() and 哈希(来源) == 哈希(镜像)
    记载(标签, 条件, f"来源={来源}；镜像={镜像}")


def 比较目录(来源: Path, 镜像: Path, 标签: str) -> None:
    来源文件 = sorted(文件 for 文件 in 来源.rglob("*") if 文件.is_file())
    异常 = []
    for 文件 in 来源文件:
        目标 = 镜像 / 文件.relative_to(来源)
        if not 目标.is_file():
            异常.append(f"缺失:{文件.relative_to(来源)}")
        elif 哈希(文件) != 哈希(目标):
            异常.append(f"漂移:{文件.relative_to(来源)}")
    记载(标签, not 异常, f"核对文件={len(来源文件)}；异常={异常[:10]}")


