def 检查两组连续性(问题: str, 包目录: Path, 分组文件名: str, 前沿文件名: str) -> None:
    分组 = pd.read_csv(包目录 / "正式候选输出" / "02_模型结果" / 分组文件名).sort_values("组别")
    前沿 = pd.read_csv(包目录 / "正式候选输出" / "02_模型结果" / 前沿文件名)
    两组 = 分组.iloc[:2]
    切点 = float(两组.iloc[0]["与下一组切点"])
    全局最小 = float(两组["组内最小BMI"].min())
    全局最大 = float(两组["组内最大BMI"].max())
    区间1 = str(两组.iloc[0]["BMI区间"])
    区间2 = str(两组.iloc[1]["BMI区间"])
    表连续 = 区间1 == f"[{全局最小:.6f},{切点:.6f})" and 区间2 == f"[{切点:.6f},{全局最大:.6f}]"
    敏感前沿 = 前沿.loc[前沿["分组方案"] == "固定两组敏感性"].copy()
    边界表 = 敏感前沿.groupby("组别")[["BMI区间下限", "BMI区间上限"]].first().sort_index()
    前沿连续 = (
        len(边界表) == 2
        and math.isclose(float(边界表.iloc[0, 0]), 全局最小, abs_tol=1e-12)
        and math.isclose(float(边界表.iloc[0, 1]), 切点, abs_tol=1e-12)
        and math.isclose(float(边界表.iloc[1, 0]), 切点, abs_tol=1e-12)
        and math.isclose(float(边界表.iloc[1, 1]), 全局最大, abs_tol=1e-12)
    )
    网格完整 = True
    for (_, _), 子表 in 前沿.groupby(["分组方案", "组别"]):
        网格完整 = 网格完整 and set(子表["检测孕周天数"].astype(int)) == set(range(70, 176))
    记载(f"{问题}BMI两组决策区间连续", 表连续 and 前沿连续, f"区间={区间1}、{区间2}；切点={切点:.9f}")
    记载(f"{问题}完整日网格风险前沿", 网格完整 and {"主分组K=1", "固定两组敏感性"}.issubset(set(前沿["分组方案"])), f"方案={sorted(前沿['分组方案'].unique())}；每组70至175天")


