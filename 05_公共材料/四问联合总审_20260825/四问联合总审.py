def 审核清单(问题: str, 路径: Path, 预期行数: int) -> None:
    if not 路径.exists():
        记载(f"{问题}审核清单存在", False, str(路径))
        return
    表 = pd.read_csv(路径)
    状态列 = "状态" if "状态" in 表.columns else None
    全通过 = 状态列 is not None and 表[状态列].astype(str).eq("通过").all()
    记载(
        f"{问题}审核清单全通过",
        len(表) == 预期行数 and 全通过,
        f"行数={len(表)}，预期={预期行数}，失败数={0 if 状态列 is None else int((表[状态列].astype(str) != '通过').sum())}",
    )


def 核验结果哈希表(问题: str, 包目录: Path, 哈希表路径: Path) -> None:
    表 = pd.read_csv(哈希表路径)
    路径列 = next(列 for 列 in 表.columns if "相对" in 列 and "路径" in 列)
    哈希列 = next(列 for 列 in 表.columns if "SHA256" in 列)
    大小列 = next(列 for 列 in 表.columns if "字节" in 列)
    根目录 = 包目录 / "正式候选输出"
    失败项 = []
    for 行 in 表.to_dict(orient="records"):
        文件 = 根目录 / str(行[路径列]).replace("\\", "/")
        if not 文件.is_file():
            失败项.append(f"缺失:{行[路径列]}")
            continue
        if 文件哈希(文件).lower() != str(行[哈希列]).lower() or 文件.stat().st_size != int(行[大小列]):
            失败项.append(f"漂移:{行[路径列]}")
    记载(f"{问题}结果文件哈希链", not 失败项, f"登记文件={len(表)}，异常={失败项[:5]}")


