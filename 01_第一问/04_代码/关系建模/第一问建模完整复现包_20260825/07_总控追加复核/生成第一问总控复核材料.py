def 文件哈希(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def 读JSON(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def 相对工作区(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(复现包目录.resolve()))
    except ValueError:
        pass
    try:
        return str(resolved.relative_to(工作区目录.resolve()))
    except ValueError:
        return str(path.name)


def 是UTF8BOM(path: Path) -> bool:
    return path.read_bytes()[:3] == b"\xef\xbb\xbf"


